-- ==========================================================================
-- Sri Products — Business Manager migration onto Supabase (Phase 5,
-- foundation). Run in the SQL Editor AFTER schema.sql, 002_delivery.sql,
-- 003_online_payment.sql. This file only lays the groundwork — tables,
-- locking/ID primitives, and staff-auth helpers — that the rest of the
-- migration (004b, 004c, ... in this same staff/ folder) builds on.
--
-- Design, so the "why" survives past this session:
--
-- 1. Staff auth uses real Supabase Auth (email/password, real bcrypt
--    hashing, real JWT sessions) instead of the Sheets version's
--    hand-rolled SHA-256 + a Sessions sheet nobody ever pruned. A
--    `staff_profiles` row (keyed by the Supabase auth user's id) is
--    how "which role is this person" and "are they still active" are
--    tracked — mirrors Code.gs's Users sheet, minus the password
--    column (Supabase Auth owns that entirely now).
--
-- 2. Every table in this migration has RLS enabled with **no policies
--    granted to anyone** — all reads and writes go through
--    SECURITY DEFINER functions that call require_staff()/require_admin()
--    themselves, exactly mirroring Code.gs's requireSession()/
--    requireAdmin() calls at the top of nearly every function. There is
--    deliberately no "authenticated users can just SELECT the sales
--    table" policy — that would make the per-function authorization
--    checks in 005/006/007 pointless, since raw table access would
--    bypass them entirely.
--
-- 3. Human-readable IDs (SALE-000123, QT-000045, etc.) are kept as a
--    unique text column generated by next_id(), same prefixes/padding
--    as Code.gs, alongside a uuid primary key used for foreign keys.
--    This is deliberate: app.js builds URLs like #/sales/SALE-000123
--    and displays these IDs throughout — keeping them means api.js can
--    stay a thin shim instead of needing to translate IDs everywhere.
--
-- 4. next_id() uses an INSERT ... ON CONFLICT DO UPDATE ... RETURNING,
--    which is atomic on its own in Postgres — no equivalent of Code.gs's
--    explicit LockService.getScriptLock() is needed here.
-- ==========================================================================

-- ---------- STAFF AUTH ----------

create table if not exists staff_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  role text not null check (role in ('Admin', 'Staff')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table staff_profiles enable row level security;
-- No policies granted here on purpose (see note 2 above). Staff read
-- their own profile via the get_current_user RPC in 004b, not by
-- selecting this table directly.

-- Returns the calling user's staff row, or raises if they're not a
-- recognized/active staff member — mirrors Code.gs's requireSession().
create or replace function require_staff() returns staff_profiles
language plpgsql
security definer
set search_path = public
as $$
declare
  v_staff staff_profiles;
begin
  if auth.uid() is null then
    raise exception 'Not authenticated.';
  end if;
  select * into v_staff from staff_profiles where id = auth.uid() and active;
  if v_staff is null then
    raise exception 'User is not active or not recognized as staff.';
  end if;
  return v_staff;
end;
$$;

-- Mirrors Code.gs's requireAdmin(). Call after require_staff() (or use
-- this alone — it calls require_staff() itself) in any function that
-- should be Admin-only.
create or replace function require_admin() returns staff_profiles
language plpgsql
security definer
set search_path = public
as $$
declare
  v_staff staff_profiles;
begin
  v_staff := require_staff();
  if v_staff.role <> 'Admin' then
    raise exception 'This action requires Admin access.';
  end if;
  return v_staff;
end;
$$;

-- Used by api.js right after login to get { userId, name, role } the
-- same shape Code.gs's login()/requireSession() returned.
create or replace function get_current_staff() returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_staff staff_profiles;
begin
  v_staff := require_staff();
  return jsonb_build_object('userId', v_staff.id, 'name', v_staff.name, 'role', v_staff.role);
end;
$$;

grant execute on function get_current_staff() to authenticated;

-- ---------- ID / COUNTER PRIMITIVES ----------

create table if not exists counters (
  prefix text primary key,
  next_number bigint not null default 0
);

create or replace function next_id(p_prefix text, p_pad_length int) returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_next bigint;
begin
  insert into counters (prefix, next_number) values (p_prefix, 1)
    on conflict (prefix) do update set next_number = counters.next_number + 1
    returning next_number into v_next;
  return p_prefix || lpad(v_next::text, p_pad_length, '0');
end;
$$;

