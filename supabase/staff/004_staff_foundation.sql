  ('logoUrl', '')
on conflict (key) do nothing;

create or replace function get_settings() returns jsonb
language sql
security definer
set search_path = public
as $$
  select coalesce(jsonb_object_agg(key, value), '{}'::jsonb) from app_settings;
$$;

create or replace function update_settings(p_updates jsonb) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_key text;
begin
  perform require_admin();
  for v_key in select jsonb_object_keys(p_updates) loop
    insert into app_settings (key, value) values (v_key, p_updates->>v_key)
      on conflict (key) do update set value = p_updates->>v_key;
  end loop;
  return get_settings();
end;
$$;

grant execute on function get_settings() to authenticated;
grant execute on function update_settings(jsonb) to authenticated;

