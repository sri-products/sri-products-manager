-- ---------- STOCK: ledger + balance primitives ----------
-- stock_balances already exists (created for the storefront:
-- item_id, balance, reserved, updated_at). Business Manager
-- operations (sales, production, manual adjustments) adjust `balance`
-- directly, same column the storefront's v_catalog reads as
-- `balance - reserved` — this is the single shared source of truth
-- for "how much stock exists" that both the storefront and the
-- Business Manager read/write from now on.

create table if not exists stock_movements (
  id uuid primary key default gen_random_uuid(),
  movement_id text not null unique,
  occurred_at timestamptz not null default now(),
  item_id uuid not null references items(id),
  quantity numeric(10,2) not null,     -- signed: negative = stock out, positive = stock in
  unit text not null,
  movement_type text not null,         -- 'Sale', 'SaleEdit', 'SaleVoid', 'Production', 'ProductionEdit', 'ProductionDelete', 'StockAdjustment'
  reference_type text,
  reference_id text,
  notes text,
  created_by text,
  created_at timestamptz not null default now()
);

alter table stock_movements enable row level security;

-- Upsert is atomic on its own — no LockService equivalent needed.
create or replace function adjust_stock_balance(p_item_id uuid, p_delta numeric) returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into stock_balances (item_id, balance, reserved, updated_at)
    values (p_item_id, p_delta, 0, now())
  on conflict (item_id) do update set balance = stock_balances.balance + p_delta, updated_at = now();
end;
$$;

-- Core primitive every domain (sales, production, adjustments) calls
-- instead of touching stock_movements/stock_balances directly —
-- mirrors Code.gs's recordStockMovement().
create or replace function record_stock_movement(
  p_item_id uuid,
  p_quantity numeric,
  p_unit text,
  p_movement_type text,
  p_reference_type text,
  p_reference_id text,
  p_notes text,
  p_created_by text
) returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_movement_id text;
begin
  v_movement_id := next_id('MOV', 6);
  insert into stock_movements (movement_id, item_id, quantity, unit, movement_type, reference_type, reference_id, notes, created_by)
  values (v_movement_id, p_item_id, p_quantity, p_unit, p_movement_type, p_reference_type, p_reference_id, coalesce(p_notes, ''), p_created_by);
  perform adjust_stock_balance(p_item_id, p_quantity);
  return v_movement_id;
end;
$$;

